"""Phase 12: validate the committed SBOMs and the dependency-audit invariants.

The SBOMs are generated by real tooling (cyclonedx-py, cyclonedx-gomod) and
checked into docs/security/. These tests validate the committed artefacts and
the release-blocking invariants WITHOUT re-running the tools, so the suite stays
green wherever the Go toolchain is absent — while still failing if a committed
SBOM goes missing/invalid, a copyleft licence appears in the Python tree, or an
unresolved row reappears in third-party.md.

Regenerate with: python backend/scripts/gen_sbom.py  (needs the `security`
extra and the Go tools on PATH).
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import pytest

_SCRIPTS = str(Path(__file__).resolve().parent.parent / "scripts")
if _SCRIPTS not in sys.path:
    sys.path.insert(0, _SCRIPTS)

import gen_sbom  # noqa: E402

SEC = gen_sbom.SEC
PY_SBOM = SEC / "sbom.cdx.json"
GO_SBOM = SEC / "sbom-sidecar.cdx.json"


def _licences(component: dict) -> list[str]:
    out = []
    for lic in component.get("licenses", []):
        node = lic.get("license", {})
        out.append(node.get("id") or node.get("name") or lic.get("expression") or "")
    return out


def test_python_sbom_is_valid_cyclonedx():
    assert PY_SBOM.exists(), "run gen_sbom.py"
    doc = json.loads(PY_SBOM.read_text())
    assert doc["bomFormat"] == "CycloneDX"
    assert doc["specVersion"].startswith("1.")
    assert len(doc["components"]) > 50
    # It must be the tool's output, not a hand-rolled document.
    tools = doc["metadata"]["tools"]
    names = ([t["name"] for t in tools] if isinstance(tools, list)
             else [c["name"] for c in tools["components"]])
    assert any("cyclonedx" in n.lower() for n in names), names


def test_go_sbom_is_valid_cyclonedx():
    assert GO_SBOM.exists(), "run gen_sbom.py"
    doc = json.loads(GO_SBOM.read_text())
    assert doc["bomFormat"] == "CycloneDX"
    assert doc["components"], "sidecar SBOM has no components"
    names = {c["name"] for c in doc["components"]}
    assert any("coraza" in n for n in names), "Coraza should appear in the Go SBOM"


def test_no_copyleft_in_python_sbom():
    """Release blocker: a GPL (non-LGPL) licence in the Python dependency tree."""
    doc = json.loads(PY_SBOM.read_text())
    bad = []
    for c in doc["components"]:
        for lic in _licences(c):
            if re.search(r"\bGPL\b", lic) and "LGPL" not in lic:
                bad.append((c["name"], lic))
    assert not bad, f"copyleft in Python deps: {bad}"


def test_third_party_inventory_has_no_unresolved_rows():
    assert gen_sbom.third_party_open_rows() == []


def test_third_party_references_the_sboms():
    tp = (gen_sbom.ROOT / "docs" / "third-party.md").read_text()
    assert "sbom.cdx.json" in tp


@pytest.mark.parametrize("name", ["starlette", "PyJWT", "sqlglot", "cryptography"])
def test_key_runtime_deps_present_with_versions(name):
    doc = json.loads(PY_SBOM.read_text())
    match = [c for c in doc["components"] if c["name"].lower() == name.lower()]
    assert match, f"{name} missing from SBOM"
    assert match[0].get("version")


# -- govulncheck parser (regression for the silent-clean bug) --------------

def test_govulncheck_parser_counts_called_not_imported():
    """The parser must count CALLED vulns (trace top-frame has a function) and
    ignore merely-imported ones. A prior bug parsed -format json as JSONL and
    always found nothing -> silent 'clean'. This locks the fix."""
    stream = """{"config": {"protocol_version": "v1.0.0"}}
{"finding": {"osv": "GO-2026-CALLED", "trace": [
  {"module": "net/http", "package": "net/http", "function": "ReadRequest"}
]}}
{"finding": {"osv": "GO-2026-IMPORTED", "trace": [
  {"module": "golang.org/x/net"}
]}}
"""
    called = gen_sbom.called_osvs(stream)
    assert called == {"GO-2026-CALLED"}


def test_govulncheck_parser_clean_on_empty():
    assert gen_sbom.called_osvs('{"config": {}}\n{"progress": {"message": "x"}}') == set()
